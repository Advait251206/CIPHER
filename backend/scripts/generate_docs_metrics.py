"""
Single source of truth for every model metric quoted in the documentation.

Reads the committed model metadata files and rewrites the blocks between
<!-- METRICS:<NAME>:START --> and <!-- METRICS:<NAME>:END --> markers in README.md
and docs/*.md. Numbers in those blocks must never be edited by hand.

Usage (from backend/):
    python -m scripts.generate_docs_metrics          # rewrite the blocks
    python -m scripts.generate_docs_metrics --check  # exit 1 if any block is stale (CI)
"""

import argparse
import json
import re
import sys
from pathlib import Path

BACKEND = Path(__file__).resolve().parent.parent
REPO = BACKEND.parent
MODELS = BACKEND / "models"

TARGET_FILES = [REPO / "README.md"] + sorted((REPO / "docs").glob("*.md"))


def _load(rel: str) -> dict:
    with open(MODELS / rel, "r", encoding="utf-8") as f:
        return json.load(f)


def pct(x: float, digits: int = 2) -> str:
    return f"{x * 100:.{digits}f}%"


def build_blocks() -> dict:
    ph = _load("phishing/model_metadata.json")
    nw = _load("network/network_model_metadata.json")
    em = _load("email/email_model_metadata.json")

    pt = ph["test_performance"]
    pcm = pt["confusion_matrix"]
    nb = nw["binary_metrics"]
    nm = nw["multiclass_metrics"]
    et = em["test_metrics"]

    summary = "\n".join([
        "| Model | Dataset (held-out test set) | Features | Accuracy | Precision | Recall | F1 | FPR |",
        "| --- | --- | --- | --- | --- | --- | --- | --- |",
        f"| Phishing URL (Random Forest) | PhiUSIIL, random stratified split ({ph['test_samples']:,} URLs) | {ph['feature_count']} | "
        f"{pct(pt['accuracy'])} | {pct(pt['precision'])} | {pct(pt['recall'])} | {pt['f1']:.4f} | {pct(pt['false_positive_rate'], 3)} |",
        f"| Network IDS, binary gate (Random Forest) | CIC-IDS2017, random stratified split ({nw['test_samples']:,} flows) | {nw['feature_count']} | "
        f"{pct(nb['accuracy'], 3)} | {pct(nb['precision'], 3)} | {pct(nb['recall'], 3)} | {nb['f1_score']:.4f} | {pct(nb['false_positive_rate'], 3)} |",
        f"| Network IDS, 9-class (Random Forest) | CIC-IDS2017, same split | {nw['feature_count']} | "
        f"{pct(nm['accuracy'], 3)} | — | — | macro {nm['macro_f1']:.4f} / weighted {nm['weighted_f1']:.4f} | — |",
        f"| Email phishing (Random Forest) | 6-corpus Kaggle aggregate, random stratified split ({em['test_samples']:,} emails) | {em['feature_count']} | "
        f"{pct(et['accuracy'])} | {pct(et['precision'])} | {pct(et['recall'])} | {et['f1_score']:.4f} | {pct(et['false_positive_rate'])} |",
        "",
        "_Generated by `backend/scripts/generate_docs_metrics.py` from the committed `models/*/…metadata.json` files. "
        "These are random-split benchmark numbers; see the limitations for why they overstate real-world performance._",
    ])

    per_class_rows = [
        "| Class | Precision | Recall | F1 | Test support |",
        "| --- | --- | --- | --- | --- |",
    ]
    for cls in nw["classes"]:
        c = nm["per_class"].get(cls)
        if not c:
            continue
        per_class_rows.append(
            f"| {cls} | {pct(c['precision'])} | {pct(c['recall'])} | {c['f1-score']:.4f} | {int(c['support']):,} |"
        )
    per_class_rows.append("")
    per_class_rows.append("_Generated from `models/network/network_model_metadata.json`._")

    phishing_cm = "\n".join([
        "```text",
        "                   Predicted Legitimate    Predicted Phishing",
        f"Actual Legitimate      {pcm['tn']:>8,} (TN)          {pcm['fp']:>6,} (FP)",
        f"Actual Phishing        {pcm['fn']:>8,} (FN)          {pcm['tp']:>6,} (TP)",
        "```",
    ])
    network_cm = "\n".join([
        "```text",
        "                   Predicted Benign        Predicted Attack",
        f"Actual Benign          {nb['true_negatives']:>8,} (TN)          {nb['false_positives']:>6,} (FP)",
        f"Actual Attack          {nb['false_negatives']:>8,} (FN)          {nb['true_positives']:>6,} (TP)",
        "```",
    ])

    return {
        "SUMMARY": summary,
        "NETWORK_PER_CLASS": "\n".join(per_class_rows),
        "PHISHING_CM": phishing_cm,
        "NETWORK_CM": network_cm,
    }


def render(text: str, blocks: dict) -> str:
    def repl(m):
        name = m.group(1)
        if name not in blocks:
            return m.group(0)
        return f"<!-- METRICS:{name}:START -->\n{blocks[name]}\n<!-- METRICS:{name}:END -->"

    return re.sub(r"<!-- METRICS:([A-Z_]+):START -->.*?<!-- METRICS:\1:END -->", repl, text, flags=re.S)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="fail if any generated block is stale")
    args = parser.parse_args()

    blocks = build_blocks()
    stale = []
    for path in TARGET_FILES:
        original = path.read_text(encoding="utf-8")
        updated = render(original, blocks)
        if updated != original:
            stale.append(path.relative_to(REPO))
            if not args.check:
                path.write_text(updated, encoding="utf-8")

    if args.check:
        if stale:
            print("Stale metric blocks (run python -m scripts.generate_docs_metrics):")
            for p in stale:
                print(f"  {p}")
            return 1
        print("All metric blocks match the committed model artifacts.")
        return 0

    print(f"Updated {len(stale)} file(s)." if stale else "Nothing to update.")
    for p in stale:
        print(f"  {p}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
